import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { EXPLANATIONS } from "../data/explanations.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const legacy = JSON.parse(fs.readFileSync(path.join(root, "data/legacy-bank.json"), "utf8"));
const categoryTag = { B: "blockers", R: "combos", A: "aggression", M: "multiway" };
const optionIds = ["a", "b", "c", "d"];
const questions = [];

legacy.DAYS.forEach((day, dayIndex) => {
  day.q.forEach((question, index) => {
    const id = `d${dayIndex + 1}q${String(index + 1).padStart(2, "0")}`;
    const revision = EXPLANATIONS[id];
    if (!revision?.explanation) throw new Error(`missing explanation for ${id}`);
    questions.push({
      id,
      legacyDay: dayIndex,
      legacyIndex: index,
      legacyCategory: question.c,
      day: dayIndex + 1,
      contentVersion: "2026.11.2",
      tags: [categoryTag[question.c], ...(revision.extraTags || [])],
      spot: question.s,
      board: revision.board || question.b,
      hand: question.h,
      prompt: question.q,
      options: question.o.map((text, optionIndex) => ({ id: optionIds[optionIndex], text })),
      correctOptionId: optionIds[question.a],
      explanation: revision.explanation,
      model: revision.model || null,
    });
  });
});

const days = legacy.DAYS.map((day, index) => ({
  day: index + 1,
  title: day.t,
  minutes: 30,
}));

const output = `// Generated by scripts/build-questions.mjs. Edit data/explanations.mjs, then rerun the script.
export const CONTENT_VERSION = "2026.11.2";
export const GAME = "6-max 無限注德州現金局，有效籌碼 100BB";
export const TAGS = {
  blockers: { label: "阻擋牌", kind: "weakness", detail: "抓詐唬和詐唬時，要分清擋到的是跟注還是棄牌" },
  combos: { label: "河牌組合計算", kind: "weakness", detail: "價值組合和詐唬組合要分開數，再和需要的勝率比" },
  aggression: { label: "攻擊性的時機", kind: "weakness", detail: "強半詐唬不夠主動，中等攤牌牌又下太兇" },
  multiway: { label: "多人底池", kind: "weakness", detail: "多人底池的持續下注過寬" },
  "pot-odds": { label: "底池賠率", kind: "strength", detail: "賠率是你的強項；答錯只記在這一題" },
};
export const DAYS = ${JSON.stringify(days, null, 2)};
export const QUESTIONS = ${JSON.stringify(questions, null, 2)};
export function questionById(id) {
  return QUESTIONS.find((question) => question.id === id) || null;
}
export function questionsForDay(day) {
  return QUESTIONS.filter((question) => question.day === day);
}
`;

fs.writeFileSync(path.join(root, "js/questions.js"), output);
console.log(`wrote ${questions.length} questions`);
